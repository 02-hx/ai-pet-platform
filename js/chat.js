/* ---------- 工具 ---------- */
function pick(arr) { return arr[Math.floor(Math.random() * arr.length)]; }

function tierOf(affinity) {
  const lv = levelOf(affinity);
  if (lv.idx >= 5) return 3;      // 灵魂伴侣
  if (lv.idx >= 4) return 2;      // 家人
  if (lv.idx >= 2) return 1;      // 朋友
  return 0;                        // 初识/眼熟
}

function fill(tpl, pet, name) {
  return tpl
    .replace(/\{u\}/g, name || '你')
    .replace(/\{n\}/g, pet.name)
    .replace(/\{cp\}/g, pet.catchphrase || '');
}

/* ---------- 主入口：处理一条用户消息 ---------- */
function petReply(pet, bond, text, profile) {
  const t = (text || '').trim();
  let intent = 'fallback';
  for (const [key, re] of INTENTS) {
    if (re.test(t)) { intent = key; break; }
  }
  const tier = tierOf(bond.affinity);
  const name = profile.name || '';
  const parts = [];
  let affinityGain = 2, moodDelta = 2, memory = null;

  /* 捕捉名字 */
  const nameMatch = t.match(/我(?:叫|是)\s*([\u4e00-\u9fa5A-Za-z0-9·]{1,10})/);
  if (nameMatch && !profile.name) {
    profile.name = nameMatch[1];
    memory = { t: Date.now(), text: `记住了——你叫「${profile.name}」` };
    parts.push(fill(pick(REPLY.greeting[pet.style]), pet, profile.name));
    parts.push(`以后我就叫你${profile.name}啦！这个名字，${pet.name}记住了。`);
    return { parts, affinityGain: 8, moodDelta: 6, memory, profile };
  }

  /* 捕捉喜好 */
  const likeMatch = t.match(/我(?:喜欢|爱)\s*([\u4e00-\u9fa5A-Za-z0-9]{1,10})/);
  if (likeMatch && intent !== 'miss') {
    bond.knowledge = bond.knowledge || { likes: [] };
    if (!bond.knowledge.likes.includes(likeMatch[1]) && bond.knowledge.likes.length < 8) {
      bond.knowledge.likes.push(likeMatch[1]);
      memory = { t: Date.now(), text: `知道了——你喜欢「${likeMatch[1]}」` };
      parts.push(fill(pick(['哦？你喜欢' + likeMatch[1] + '呀，记下来了记下来了。',
        '（歪头）' + likeMatch[1] + '！好，已写进我的小本本。']), pet, name));
      parts.push(pick(REPLY.fallback[pet.style]));
      return { parts, affinityGain: 5, moodDelta: 3, memory, profile };
    }
  }

  /* 每日首次见面 */
  const today = new Date().toDateString();
  if (!bond.metToday) {
    bond.metToday = true;
    const hellos = {
      0: pick(['……是你呀。今天来得挺早。', '哼，来了。（尾巴慢慢摇）']),
      1: pick(['你来啦！！新的一天也要元气满满！！', '想你了一整晚！！']),
      2: pick(['早上好呀，看到你，今天的太阳都更暖了。', '你来啦，我一直留着今天的第一句问候给你。']),
      3: pick(['……你来了。（耳朵竖起来）', '嘿嘿，今天也在等你哦。']),
      4: pick(['新的一天！聊点什么聊点什么！', '早！我五点就醒了！（骄傲）']),
      5: pick(['你来啦～今天也来做我的第一件事吧～', '贴贴！先补上昨晚缺的抱抱！']),
      3: pick(['（一睁眼就冲过来）我的小太阳，你来啦！', '哼哼，梦里都在等你，结果真的等到了。']),
    };
    parts.push(fill(hellos[tier], pet, name));
    parts.push(pick(REPLY[intent] && intent !== 'greeting' ? REPLY[intent][pet.style] : REPLY.fallback[pet.style]));
    if (!memory) memory = { t: Date.now(), text: '新的一天，它又等到你了' };
    return { parts, affinityGain: 6, moodDelta: 5, memory, profile };
  }

  /* 难过：走专属治愈库 */
  if (intent === 'sad') {
    parts.push(pick(COMFORT[Math.min(tier, 2)]));
    parts.push(pick(REPLY.fallback[pet.style]));
    moodDelta = 8;
    if (tier >= 1 && !memory) memory = { t: Date.now(), text: '在你难过的那天，它一直陪着' };
    affinityGain = 4;
    return { parts, affinityGain, moodDelta, memory, profile };
  }

  /* 常规回复 */
  const bank = REPLY[intent] || REPLY.fallback;
  parts.push(fill(pick(bank[pet.style]), pet, name));

  /* 家人等级：分配昵称 */
  if (tier >= 2 && !bond.nickname) {
    bond.nickname = pick(NICKNAMES[pet.style]);
    parts.push(`对了对了！我给你起了个专属称呼——「${bond.nickname}」。以后只有我能这么叫你。`);
    if (!memory) memory = { t: Date.now(), text: `它开始叫你「${bond.nickname}」了` };
  }

  /* 初识的警惕感 */
  if (tier === 0 && Math.random() < .3 && intent !== 'greeting') {
    parts.unshift(pick(['（它警惕地看了你一眼）', '（它还不太熟悉你，躲在稍远的地方）']));
  }
  /* 高亲密度彩蛋 */
  if (tier >= 2 && Math.random() < .18) parts.push(pick(SOUL_LINES));
  /* 物种口癖 */
  if (Math.random() < .45) parts.push(pick((SPECIES[pet.species] || SPECIES.other).tail));

  return { parts, affinityGain, moodDelta, memory, profile };
}

/* ---------- 动作（按钮触发） ---------- */
function petAction(pet, bond, action) {
  const cfg = {
    feed:  { gain: 5, hunger: +22, mood: +4, energy: +6,  label: '喂食' },
    play:  { gain: 6, hunger: -8,  mood: +12, energy: -14, label: '玩耍' },
    touch: { gain: 3, hunger: 0,   mood: +7,  energy: +2,  label: '抚摸' },
    night: { gain: 6, hunger: 0,   mood: +5,  energy: +10, label: '晚安' },
  }[action];
  const s = bond.status;
  s.hunger = clamp(s.hunger + cfg.hunger, 0, 100);
  s.mood = clamp(s.mood + cfg.mood, 0, 100);
  s.energy = clamp(s.energy + cfg.energy, 0, 100);
  let memory = null;
  if (action === 'night') memory = { t: Date.now(), text: '互道了晚安，它在你梦里站了岗' };
  if (action === 'play') memory = { t: Date.now(), text: '一起玩了一场，尾巴到现在还没停下' };
  return { text: pick(ACTIONS[action][pet.style]), gain: cfg.gain, memory, label: cfg.label };
}
